import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { AccessLevel, ExamType } from '@prisma/client';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsBoolean,
  IsEnum,
  IsInt,
  IsNumber,
  IsOptional,
  IsString,
  Matches,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { Trim, TrimToNull } from '../../../common/dto/transforms';

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

export class ExamSettingsDto {
  @ApiProperty({ minimum: 1, maximum: 200 })
  @IsInt()
  @Min(1)
  @Max(200)
  questionCount: number;

  @ApiProperty({ minimum: 1, maximum: 300 })
  @IsInt()
  @Min(1)
  @Max(300)
  durationMinutes: number;

  @ApiProperty({ minimum: 0.25, maximum: 10 })
  @IsNumber()
  @Min(0.25)
  @Max(10)
  marksPerQuestion: number;

  @ApiProperty({ minimum: 0, maximum: 10 })
  @IsNumber()
  @Min(0)
  @Max(10)
  negativeMarking: number;

  @ApiProperty()
  @IsBoolean()
  allowMultipleAttempts: boolean;

  @ApiProperty({ description: "Create today's daily exam automatically when none is published" })
  @IsBoolean()
  autoGenerateDaily: boolean;
}

class ExamConfigFields {
  @ApiPropertyOptional()
  @TrimToNull()
  @IsString()
  @MaxLength(1000)
  @IsOptional()
  description?: string | null;

  @ApiPropertyOptional({ minimum: 1, maximum: 300 })
  @IsInt()
  @Min(1)
  @Max(300)
  @IsOptional()
  durationMinutes?: number;

  @ApiPropertyOptional({ minimum: 0.25, maximum: 10 })
  @IsNumber()
  @Min(0.25)
  @Max(10)
  @IsOptional()
  marksPerQuestion?: number;

  @ApiPropertyOptional({ minimum: 0, maximum: 10 })
  @IsNumber()
  @Min(0)
  @Max(10)
  @IsOptional()
  negativeMarking?: number;

  @ApiPropertyOptional()
  @IsBoolean()
  @IsOptional()
  allowMultipleAttempts?: boolean;

  @ApiPropertyOptional({ enum: AccessLevel })
  @IsEnum(AccessLevel)
  @IsOptional()
  accessLevel?: AccessLevel;

  @ApiPropertyOptional()
  @IsBoolean()
  @IsOptional()
  isPublished?: boolean;

  @ApiPropertyOptional({ enum: ExamType })
  @IsEnum(ExamType)
  @IsOptional()
  type?: ExamType;

  @ApiPropertyOptional({ example: '2026-11-04', description: 'Business date (Asia/Dhaka)' })
  @Matches(ISO_DATE, { message: 'examDate must be in YYYY-MM-DD format' })
  @IsOptional()
  examDate?: string;
}

export class QuestionSelectionDto {
  @ApiPropertyOptional({ minimum: 1, maximum: 200, description: 'Defaults to the exam settings' })
  @IsInt()
  @Min(1)
  @Max(200)
  @IsOptional()
  questionCount?: number;

  @ApiPropertyOptional({ type: [String], description: 'Limit random selection to these subjects' })
  @IsArray()
  @IsString({ each: true })
  @ArrayMaxSize(50)
  @IsOptional()
  subjectIds?: string[];

  @ApiPropertyOptional({
    type: [String],
    description: 'Explicit questions (overrides random selection)',
  })
  @IsArray()
  @IsString({ each: true })
  @ArrayMaxSize(200)
  @IsOptional()
  questionIds?: string[];
}

export class CreateExamDto extends ExamConfigFields {
  @ApiPropertyOptional({
    example: 'Daily Exam — ICT',
    description: 'Defaults to "Daily Exam — <date>"',
  })
  @TrimToNull()
  @IsString()
  @MinLength(3)
  @MaxLength(150)
  @IsOptional()
  title?: string | null;

  @ApiPropertyOptional({ type: QuestionSelectionDto })
  @ValidateNested()
  @Type(() => QuestionSelectionDto)
  @IsOptional()
  selection?: QuestionSelectionDto;
}

export class UpdateExamDto extends ExamConfigFields {
  @ApiPropertyOptional()
  @Trim()
  @IsString()
  @MinLength(3)
  @MaxLength(150)
  @IsOptional()
  title?: string;
}

export class SaveAnswerDto {
  @ApiProperty()
  @IsString()
  answerId: string;

  @ApiPropertyOptional({ nullable: true, description: 'null clears the answer' })
  @IsString()
  @IsOptional()
  selectedOptionId: string | null;
}

export class SubmitAttemptDto {
  @ApiPropertyOptional({
    type: [SaveAnswerDto],
    description: 'Final answers flushed with the submission',
  })
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => SaveAnswerDto)
  @ArrayMaxSize(200)
  @IsOptional()
  answers?: SaveAnswerDto[];
}
