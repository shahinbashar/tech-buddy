import { BadRequestException, Injectable, Logger } from '@nestjs/common';
import { type AccessLevel, type ExamSettings, Prisma } from '@prisma/client';
import { PrismaService } from '../../prisma/prisma.service';
import { dhakaDate } from '../../common/utils/dhaka-time';
import { shuffle } from '../../common/utils/shuffle';

const SETTINGS_ID = 1;

/** Owns exam settings, random question selection and automatic daily-exam creation. */
@Injectable()
export class ExamGeneratorService {
  private readonly logger = new Logger(ExamGeneratorService.name);

  constructor(private readonly prisma: PrismaService) {}

  getSettings(): Promise<ExamSettings> {
    return this.prisma.examSettings.upsert({
      where: { id: SETTINGS_ID },
      create: { id: SETTINGS_ID },
      update: {},
    });
  }

  updateSettings(data: Omit<ExamSettings, 'id' | 'updatedAt'>): Promise<ExamSettings> {
    return this.prisma.examSettings.upsert({
      where: { id: SETTINGS_ID },
      create: { id: SETTINGS_ID, ...data },
      update: data,
    });
  }

  /**
   * Picks `count` random published questions. FREE exams only use FREE questions so that
   * free users never see premium questions.
   */
  async pickRandomQuestionIds(
    count: number,
    accessLevel: AccessLevel,
    subjectIds?: string[],
  ): Promise<string[]> {
    const pool = await this.prisma.question.findMany({
      where: {
        isPublished: true,
        ...(accessLevel === 'FREE' ? { accessLevel: 'FREE' } : {}),
        ...(subjectIds?.length ? { subjectId: { in: subjectIds } } : {}),
      },
      select: { id: true },
    });
    return shuffle(pool.map((q) => q.id)).slice(0, count);
  }

  async assertQuestionsUsable(questionIds: string[], accessLevel: AccessLevel): Promise<void> {
    const unique = [...new Set(questionIds)];
    if (unique.length !== questionIds.length)
      throw new BadRequestException('Duplicate questions selected');
    const found = await this.prisma.question.findMany({
      where: { id: { in: unique }, isPublished: true },
      select: { accessLevel: true },
    });
    if (found.length !== unique.length) {
      throw new BadRequestException('Some selected questions do not exist or are not published');
    }
    if (accessLevel === 'FREE' && found.some((q) => q.accessLevel === 'PREMIUM')) {
      throw new BadRequestException('A free exam cannot contain premium questions');
    }
  }

  /**
   * Ensures today's daily exam exists when auto-generation is enabled and no published
   * daily exam was scheduled by an admin. Safe under concurrency via the unique
   * `autoGeneratedFor` column.
   */
  async ensureTodaysDailyExam(): Promise<void> {
    const settings = await this.getSettings();
    if (!settings.autoGenerateDaily) return;

    const today = dhakaDate();
    const existing = await this.prisma.exam.count({
      where: {
        OR: [{ autoGeneratedFor: today }, { type: 'DAILY', examDate: today, isPublished: true }],
      },
    });
    if (existing) return;

    const questionIds = await this.pickRandomQuestionIds(settings.questionCount, 'FREE');
    if (!questionIds.length) return;

    try {
      await this.prisma.exam.create({
        data: {
          title: `Daily Exam — ${today.toISOString().slice(0, 10)}`,
          description: 'Automatically generated daily practice exam.',
          type: 'DAILY',
          examDate: today,
          autoGeneratedFor: today,
          durationMinutes: settings.durationMinutes,
          marksPerQuestion: settings.marksPerQuestion,
          negativeMarking: settings.negativeMarking,
          allowMultipleAttempts: settings.allowMultipleAttempts,
          accessLevel: 'FREE',
          isPublished: true,
          questions: { create: questionIds.map((questionId, order) => ({ questionId, order })) },
        },
      });
      this.logger.log(`Auto-generated daily exam for ${today.toISOString().slice(0, 10)}`);
    } catch (error) {
      // Another request created it first.
      if (error instanceof Prisma.PrismaClientKnownRequestError && error.code === 'P2002') return;
      throw error;
    }
  }
}
