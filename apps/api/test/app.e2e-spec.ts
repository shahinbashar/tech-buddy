import { type NestExpressApplication } from '@nestjs/platform-express';
import { Test } from '@nestjs/testing';
import request from 'supertest';
import { type App } from 'supertest/types';
import { AppModule } from '../src/app.module';
import { configureApp } from '../src/app.setup';
import { hashPassword } from '../src/modules/auth/password';
import { PrismaService } from '../src/prisma/prisma.service';

/**
 * Key user flows against a real database (isolated `e2e` schema, reset per run):
 * authentication, authorization, premium gating and the full exam lifecycle.
 */
describe('Tech Buddy API (e2e)', () => {
  let app: NestExpressApplication;
  let prisma: PrismaService;
  let server: App;
  let premiumNoteTopicSlug: string;
  /** Unique per run so the suite can be re-run against the same database. */
  const RUN = Date.now().toString(36);
  const ADMIN = { email: `admin-${RUN}@e2e.test`, password: 'AdminPass123' };
  const SUBJECT_SLUG = `cs-${RUN}`;
  const PAPER = `Past paper ${RUN}`;
  let counter = 0;

  const agent = () => request.agent(server);

  async function registeredAgent() {
    const a = agent();
    const email = `user${++counter}-${RUN}@e2e.test`;
    await a
      .post('/api/auth/register')
      .send({ fullName: 'E2E User', email, password: 'Secret123' })
      .expect(201);
    return { agent: a, email };
  }

  async function adminAgent() {
    const a = agent();
    await a.post('/api/auth/login').send(ADMIN).expect(200);
    return a;
  }

  beforeAll(async () => {
    const moduleRef = await Test.createTestingModule({ imports: [AppModule] }).compile();
    app = moduleRef.createNestApplication<NestExpressApplication>();
    configureApp(app);
    await app.init();
    server = app.getHttpServer() as App;
    prisma = app.get(PrismaService);

    await prisma.user.create({
      data: {
        email: ADMIN.email,
        fullName: 'E2E Admin',
        role: 'ADMIN',
        passwordHash: await hashPassword(ADMIN.password),
      },
    });
    const subject = await prisma.subject.create({
      data: { slug: SUBJECT_SLUG, name: `Computer Science ${RUN}`, isPublished: true },
    });
    const topic = await prisma.topic.create({
      data: { subjectId: subject.id, slug: 'logic', title: 'Logic', isPublished: true },
    });
    premiumNoteTopicSlug = topic.slug;
    await prisma.note.create({
      data: {
        topicId: topic.id,
        title: 'Premium deep dive',
        content: 'SECRET PREMIUM CONTENT',
        accessLevel: 'PREMIUM',
        isPublished: true,
      },
    });
    for (let i = 0; i < 6; i++) {
      await prisma.question.create({
        data: {
          subjectId: subject.id,
          topicId: topic.id,
          text: `Question ${i}?`,
          explanation: `Because ${i}`,
          reference: PAPER,
          isPublished: true,
          accessLevel: i === 5 ? 'PREMIUM' : 'FREE',
          options: {
            create: ['A', 'B', 'C', 'D'].map((text, order) => ({
              text: `${text}${i}`,
              order,
              isCorrect: order === 0,
            })),
          },
        },
      });
    }
    const settings = { questionCount: 3, durationMinutes: 5, autoGenerateDaily: true };
    await prisma.examSettings.upsert({
      where: { id: 1 },
      create: { id: 1, ...settings },
      update: settings,
    });
  });

  afterAll(async () => {
    await app.close();
  });

  describe('auth', () => {
    it('registers with an httpOnly cookie and never returns the password hash or token', async () => {
      const res = await agent()
        .post('/api/auth/register')
        .send({ fullName: 'Cookie Check', email: `Cookie-${RUN}@E2E.test`, password: 'Secret123' })
        .expect(201);
      const cookie = String(res.headers['set-cookie']);
      expect(cookie).toContain('tb_access_token=');
      expect(cookie).toContain('HttpOnly');
      expect(res.body.user.email).toBe(`cookie-${RUN}@e2e.test`);
      expect(JSON.stringify(res.body)).not.toMatch(/passwordHash|accessToken/);
    });

    it('rejects duplicate emails, unknown fields and weak passwords', async () => {
      await agent()
        .post('/api/auth/register')
        .send({ fullName: 'Dup', email: `cookie-${RUN}@e2e.test`, password: 'Secret123' })
        .expect(409);
      const res = await agent()
        .post('/api/auth/register')
        .send({ fullName: 'Hacker', email: 'h@e2e.test', password: 'weak', role: 'ADMIN' })
        .expect(400);
      expect(res.body.message).toEqual(expect.arrayContaining(['property role should not exist']));
    });

    it('uses one generic message for unknown email and wrong password', async () => {
      const unknown = await agent()
        .post('/api/auth/login')
        .send({ email: 'nobody@e2e.test', password: 'Secret123' })
        .expect(401);
      const wrong = await agent()
        .post('/api/auth/login')
        .send({ email: ADMIN.email, password: 'Wrong12345' })
        .expect(401);
      expect(unknown.body.message).toBe(wrong.body.message);
    });

    it('revokes other sessions when the password changes', async () => {
      const { agent: first, email } = await registeredAgent();
      const second = agent();
      await second.post('/api/auth/login').send({ email, password: 'Secret123' }).expect(200);

      await first
        .post('/api/auth/password')
        .send({ currentPassword: 'Secret123', newPassword: 'Changed123' })
        .expect(204);

      await first.get('/api/auth/me').expect(200);
      await second.get('/api/auth/me').expect(401);
    });
  });

  describe('authorization', () => {
    it('requires a session for private routes and the admin role for admin routes', async () => {
      await agent().get('/api/dashboard/me').expect(401);
      const { agent: user } = await registeredAgent();
      await user.get('/api/admin/users').expect(403);
      await (await adminAgent()).get('/api/admin/users').expect(200);
    });

    it('signs out a user immediately when an admin deactivates them', async () => {
      const { agent: user } = await registeredAgent();
      const me = await user.get('/api/auth/me').expect(200);
      const admin = await adminAgent();
      await admin
        .patch(`/api/admin/users/${me.body.id}/status`)
        .send({ isActive: false })
        .expect(200);
      await user.get('/api/auth/me').expect(401);
    });
  });

  describe('premium gating', () => {
    it('hides premium note content until access is granted', async () => {
      const { agent: user } = await registeredAgent();
      const path = `/api/subjects/${SUBJECT_SLUG}/topics/${premiumNoteTopicSlug}`;

      const locked = await user.get(path).expect(200);
      expect(locked.body.notes[0]).toMatchObject({ isLocked: true, content: null });
      expect(JSON.stringify(locked.body)).not.toContain('SECRET PREMIUM CONTENT');

      const me = await user.get('/api/auth/me');
      await (await adminAgent())
        .post('/api/admin/entitlements')
        .send({ userId: me.body.id })
        .expect(201);

      const unlocked = await user.get(path).expect(200);
      expect(unlocked.body.notes[0].content).toBe('SECRET PREMIUM CONTENT');
    });
  });

  describe('daily exam lifecycle', () => {
    it('auto-generates today’s exam from free questions only', async () => {
      const { agent: user } = await registeredAgent();
      const res = await user.get('/api/exams/today').expect(200);
      expect(res.body.length).toBeGreaterThanOrEqual(1);
      expect(res.body[0]).toMatchObject({ accessLevel: 'FREE', canStart: true });

      const exam = await prisma.exam.findFirstOrThrow({
        where: { id: res.body[0].id },
        include: { questions: { include: { question: true } } },
      });
      expect(exam.questions.every((q) => q.question.accessLevel === 'FREE')).toBe(true);
    });

    it('runs start → answer → submit with server-side scoring and no answer leakage', async () => {
      const { agent: user } = await registeredAgent();
      const [exam] = (await user.get('/api/exams/today')).body as { id: string }[];

      // Parallel starts (double click) resolve to the same attempt.
      const [a, b] = await Promise.all([
        user.post(`/api/exams/${exam.id}/attempts`),
        user.post(`/api/exams/${exam.id}/attempts`),
      ]);
      expect(a.body.attemptId).toBe(b.body.attemptId);
      const attemptId = a.body.attemptId as string;

      const inProgress = await user.get(`/api/attempts/${attemptId}`).expect(200);
      expect(inProgress.body.status).toBe('IN_PROGRESS');
      expect(JSON.stringify(inProgress.body)).not.toMatch(/correctOptionId|explanation|isCorrect/);

      type Q = { answerId: string; options: { id: string; text: string }[] };
      const [q1, q2] = inProgress.body.questions as Q[];
      const correctOf = (q: Q) => q.options.find((o) => /^A\d$/.test(o.text))!.id;
      const wrongOf = (q: Q) => q.options.find((o) => /^B\d$/.test(o.text))!.id;

      await user
        .put(`/api/attempts/${attemptId}/answers`)
        .send({ answerId: q1.answerId, selectedOptionId: q2.options[0].id })
        .expect(400);
      await user
        .put(`/api/attempts/${attemptId}/answers`)
        .send({ answerId: q1.answerId, selectedOptionId: correctOf(q1) })
        .expect(200);

      const result = await user
        .post(`/api/attempts/${attemptId}/submit`)
        .send({ answers: [{ answerId: q2.answerId, selectedOptionId: wrongOf(q2) }] })
        .expect(200);
      expect(result.body.status).toBe('SUBMITTED');
      expect(result.body.result).toMatchObject({
        correctCount: 1,
        incorrectCount: 1,
        unansweredCount: 1,
        obtainedMarks: 1,
      });
      expect(result.body.questions[0]).toHaveProperty('correctOptionId');

      await user
        .put(`/api/attempts/${attemptId}/answers`)
        .send({ answerId: q1.answerId, selectedOptionId: null })
        .expect(400);
      await user.post(`/api/exams/${exam.id}/attempts`).expect(400);

      const { agent: stranger } = await registeredAgent();
      await stranger.get(`/api/attempts/${attemptId}`).expect(404);
    });

    it('finalizes an expired attempt on read and rejects late answers', async () => {
      const { agent: user } = await registeredAgent();
      const [exam] = (await user.get('/api/exams/today')).body as { id: string }[];
      const { attemptId } = (await user.post(`/api/exams/${exam.id}/attempts`)).body as {
        attemptId: string;
      };
      const view = await user.get(`/api/attempts/${attemptId}`);
      await prisma.examAttempt.update({
        where: { id: attemptId },
        data: { expiresAt: new Date(Date.now() - 60_000) },
      });

      await user
        .put(`/api/attempts/${attemptId}/answers`)
        .send({ answerId: view.body.questions[0].answerId, selectedOptionId: null })
        .expect(400);
      const expired = await user.get(`/api/attempts/${attemptId}`).expect(200);
      expect(expired.body.status).toBe('SUBMITTED');
      expect(expired.body.result.unansweredCount).toBe(expired.body.result.totalQuestions);
    });
  });

  describe('audit features', () => {
    it('saves circulars and lists them closing soonest first', async () => {
      const circular = await prisma.jobCircular.create({
        data: {
          slug: `saved-${RUN}`,
          organizationName: 'E2E Org',
          title: 'Programmer',
          publishedDate: new Date(),
          applicationStartDate: new Date(),
          applicationDeadline: new Date(Date.now() + 3 * 86_400_000),
          isPublished: true,
        },
      });
      const { agent: user } = await registeredAgent();
      await user.put(`/api/circulars/${circular.id}/save`).expect(200);
      await user.put(`/api/circulars/${circular.id}/save`).expect(200); // idempotent

      const detail = await user.get(`/api/circulars/${circular.slug}`).expect(200);
      expect(detail.body.isSaved).toBe(true);
      const saved = await user.get('/api/circulars/saved').expect(200);
      expect((saved.body as { id: string }[]).map((c) => c.id)).toEqual([circular.id]);
      const dashboard = await user.get('/api/dashboard/me').expect(200);
      expect(dashboard.body.savedClosingSoon[0].id).toBe(circular.id);

      await user.delete(`/api/circulars/${circular.id}/save`).expect(204);
      expect((await user.get('/api/circulars/saved')).body).toEqual([]);
      await agent().get('/api/circulars/saved').expect(401);
    });

    it('recommends open circulars for the goal and leaves out saved ones', async () => {
      const { agent: user } = await registeredAgent();
      const soon = (hours: number) => new Date(Date.now() + hours * 3_600_000);
      const base = {
        organizationName: 'E2E Bank',
        publishedDate: new Date(),
        applicationStartDate: new Date(Date.now() - 60_000),
        isPublished: true,
      };
      const [bank, saved, it] = await Promise.all([
        prisma.jobCircular.create({
          data: {
            ...base,
            slug: `rec-bank-${RUN}`,
            title: 'Officer',
            category: 'BANK',
            applicationDeadline: soon(1),
          },
        }),
        prisma.jobCircular.create({
          data: {
            ...base,
            slug: `rec-saved-${RUN}`,
            title: 'Cash Officer',
            category: 'BANK',
            applicationDeadline: soon(1),
          },
        }),
        prisma.jobCircular.create({
          data: {
            ...base,
            slug: `rec-it-${RUN}`,
            title: 'Programmer',
            category: 'IT',
            applicationDeadline: soon(1),
          },
        }),
      ]);
      await user.patch('/api/users/me').send({ preparationGoal: 'BANK' }).expect(200);
      await user.put(`/api/circulars/${saved.id}/save`).expect(200);

      const { body } = await user.get('/api/dashboard/me').expect(200);
      const ids = (body.recommendedCirculars as { id: string }[]).map((c) => c.id);
      expect(body.preparationGoal).toBe('BANK');
      expect(body.overview.savedCirculars).toBe(1);
      expect(ids).toContain(bank.id);
      expect(ids).not.toContain(saved.id); // already saved
      expect(ids).not.toContain(it.id); // other goal
    });

    it('creates private practice sets, including a "my mistakes" set', async () => {
      const { agent: user } = await registeredAgent();
      await user.post('/api/practice').send({ mode: 'mistakes', questionCount: 5 }).expect(400);

      // Answer today's exam wrong so there are mistakes to practise.
      const [exam] = (await user.get('/api/exams/today')).body as { id: string }[];
      const { attemptId } = (await user.post(`/api/exams/${exam.id}/attempts`)).body as {
        attemptId: string;
      };
      const view = await user.get(`/api/attempts/${attemptId}`);
      type Q = { answerId: string; options: { id: string; text: string }[] };
      const answers = (view.body.questions as Q[]).map((q) => ({
        answerId: q.answerId,
        selectedOptionId: q.options.find((o) => /^B\d$/.test(o.text))!.id,
      }));
      await user.post(`/api/attempts/${attemptId}/submit`).send({ answers }).expect(200);

      const mistakes = await user
        .post('/api/practice')
        .send({ mode: 'mistakes', questionCount: 5 })
        .expect(201);
      expect(mistakes.body.questionCount).toBe(answers.length);
      const practiceView = await user.get(`/api/attempts/${mistakes.body.attemptId}`).expect(200);
      expect(practiceView.body.examTitle).toMatch(/^Mistakes practice/);

      const random = await user.post('/api/practice').send({ questionCount: 5 }).expect(201);
      expect(random.body.questionCount).toBe(5);

      // Practice sets are private: not listed publicly, not visible to others, not ranked.
      const practiceExamId = practiceView.body.exam.id as string;
      const listed = (await user.get('/api/exams?pageSize=100')).body.items as { id: string }[];
      expect(listed.some((e) => e.id === practiceExamId)).toBe(false);
      const { agent: other } = await registeredAgent();
      await other.get(`/api/exams/${practiceExamId}`).expect(404);
      await other.post(`/api/exams/${practiceExamId}/attempts`).expect(404);
      await user.get(`/api/exams/${practiceExamId}/leaderboard`).expect(404);
    });

    it('lists past papers and practises one, counting only accessible questions', async () => {
      const { agent: user } = await registeredAgent();
      const sources = (await user.get('/api/practice/sources').expect(200)).body as {
        reference: string;
        questionCount: number;
        availableCount: number;
      }[];
      // Five free questions plus one premium question the free user cannot draw.
      expect(sources.find((s) => s.reference === PAPER)).toEqual({
        reference: PAPER,
        questionCount: 6,
        availableCount: 5,
      });

      const paper = await user
        .post('/api/practice')
        .send({ reference: `  ${PAPER} `, questionCount: 50 })
        .expect(201);
      expect(paper.body.questionCount).toBe(5);
      const view = await user.get(`/api/attempts/${paper.body.attemptId}`).expect(200);
      expect(view.body.examTitle).toBe(`Practice — ${PAPER}`);

      await user
        .post('/api/practice')
        .send({ reference: `Unknown ${RUN}`, questionCount: 5 })
        .expect(400);
      await agent().get('/api/practice/sources').expect(401);
    });

    it('ranks first attempts on the leaderboard', async () => {
      const { agent: user } = await registeredAgent();
      const [exam] = (await user.get('/api/exams/today')).body as { id: string }[];
      const { attemptId } = (await user.post(`/api/exams/${exam.id}/attempts`)).body as {
        attemptId: string;
      };
      await user.post(`/api/attempts/${attemptId}/submit`).send({}).expect(200);

      const board = await user.get(`/api/exams/${exam.id}/leaderboard`).expect(200);
      expect(board.body.participants).toBeGreaterThanOrEqual(1);
      expect(board.body.me).toMatchObject({ isMe: true, name: 'E2E U.' });
      expect(board.body.me.topPercent).toBeGreaterThan(0);
      expect(JSON.stringify(board.body)).not.toMatch(/userId|@e2e\.test/);
    });
  });

  describe('mobile token auth', () => {
    it('issues bearer + refresh tokens, rotates them, and never accepts a refresh token as access', async () => {
      const email = `mobile-${RUN}@e2e.test`;
      const registered = await agent()
        .post('/api/auth/mobile/register')
        .send({ fullName: 'Mobile User', email, password: 'Secret123' })
        .expect(201);
      expect(registered.headers['set-cookie']).toBeUndefined();
      const { accessToken, refreshToken } = registered.body as {
        accessToken: string;
        refreshToken: string;
      };
      expect(accessToken).toBeTruthy();
      expect(refreshToken).toBeTruthy();

      await agent().get('/api/auth/me').set('Authorization', `Bearer ${accessToken}`).expect(200);
      await agent().get('/api/auth/me').set('Authorization', `Bearer ${refreshToken}`).expect(401);

      const refreshed = await agent()
        .post('/api/auth/mobile/refresh')
        .send({ refreshToken })
        .expect(200);
      await agent()
        .get('/api/dashboard/me')
        .set('Authorization', `Bearer ${refreshed.body.accessToken}`)
        .expect(200);
      await agent()
        .post('/api/auth/mobile/refresh')
        .send({ refreshToken: accessToken })
        .expect(401);

      // Changing the password revokes every session, including mobile refresh tokens.
      await agent()
        .post('/api/auth/password')
        .set('Authorization', `Bearer ${refreshed.body.accessToken}`)
        .send({ currentPassword: 'Secret123', newPassword: 'Changed123' })
        .expect(204);
      await agent()
        .post('/api/auth/mobile/refresh')
        .send({ refreshToken: refreshed.body.refreshToken })
        .expect(401);

      const login = await agent()
        .post('/api/auth/mobile/login')
        .send({ email, password: 'Changed123' })
        .expect(200);
      expect(login.body.user.email).toBe(email);
    });
  });
});
