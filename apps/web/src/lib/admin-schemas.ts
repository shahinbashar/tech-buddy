import { z } from 'zod';

const optionalText = (max: number) => z.string().trim().max(max);
const accessLevel = z.enum(['FREE', 'PREMIUM']);

// ── Circular ──
export const circularSchema = z
  .object({
    organizationName: z.string().trim().min(2, 'Organization is required').max(200),
    organizationNameBn: optionalText(200),
    title: z.string().trim().min(2, 'Designation is required').max(200),
    category: z.enum([
      'IT',
      'BANK',
      'EDUCATION',
      'HEALTH',
      'ENGINEERING',
      'ADMINISTRATION',
      'DEFENSE',
      'OTHER',
    ]),
    jobType: z.enum(['GOVERNMENT', 'PRIVATE']),
    employmentType: z.enum(['FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERNSHIP']),
    publishedDate: z.string().min(1, 'Published date is required'),
    applicationStartDate: z.string().min(1, 'Start date is required'),
    applicationDeadline: z.string().min(1, 'Deadline is required'),
    vacancies: z.number().int().min(0).nullable(),
    salary: optionalText(200),
    educationalQualification: optionalText(5000),
    ageRequirement: optionalText(1000),
    additionalRequirements: optionalText(10000),
    applicationInstructions: optionalText(10000),
    applicationUrl: z.union([
      z.literal(''),
      z.url({ protocol: /^https?$/, message: 'Enter a valid http(s) URL' }),
    ]),
    isFeatured: z.boolean(),
    isPublished: z.boolean(),
  })
  .refine((v) => v.applicationStartDate <= v.applicationDeadline, {
    path: ['applicationDeadline'],
    message: 'Deadline must be after the start date',
  });
export type CircularFormValues = z.infer<typeof circularSchema>;

// ── Subject ──
export const subjectSchema = z.object({
  name: z.string().trim().min(2, 'Name is required').max(100),
  nameBn: optionalText(100),
  description: optionalText(1000),
  category: z.enum(['GENERAL', 'TECHNICAL']),
  order: z.number().int().min(0),
  isPublished: z.boolean(),
});
export type SubjectFormValues = z.infer<typeof subjectSchema>;

// ── Topic ──
export const topicSchema = z.object({
  subjectId: z.string().min(1, 'Choose a subject'),
  parentId: z.string().nullable(),
  title: z.string().trim().min(2, 'Title is required').max(150),
  description: optionalText(1000),
  content: optionalText(100_000),
  accessLevel,
  isPublished: z.boolean(),
  order: z.number().int().min(0),
});
export type TopicFormValues = z.infer<typeof topicSchema>;

// ── Note ──
export const noteSchema = z.object({
  subjectId: z.string().min(1, 'Choose a subject'),
  topicId: z.string().min(1, 'Choose a topic'),
  title: z.string().trim().min(2, 'Title is required').max(200),
  summary: optionalText(500),
  content: z.string().min(1, 'Content is required').max(200_000),
  accessLevel,
  isPublished: z.boolean(),
  order: z.number().int().min(0),
});
export type NoteFormValues = z.infer<typeof noteSchema>;

// ── Question ──
export const questionSchema = z
  .object({
    subjectId: z.string().min(1, 'Choose a subject'),
    topicId: z.string().nullable(),
    text: z.string().trim().min(3, 'Question text is required').max(2000),
    textBn: optionalText(2000),
    difficulty: z.enum(['EASY', 'MEDIUM', 'HARD']),
    options: z
      .array(
        z.object({
          text: z.string().trim().min(1, 'Option is required').max(500),
          textBn: optionalText(500),
        }),
      )
      .length(4),
    correctOptionIndex: z.string().regex(/^[0-3]$/, 'Choose the correct answer'),
    explanation: z.string().trim().min(1, 'Explanation is required').max(5000),
    reference: optionalText(500),
    accessLevel,
    isPublished: z.boolean(),
  })
  .refine((v) => new Set(v.options.map((o) => o.text.trim().toLowerCase())).size === 4, {
    path: ['options'],
    message: 'Options must be distinct',
  });
export type QuestionFormValues = z.infer<typeof questionSchema>;

// ── Exams ──
export const examSettingsSchema = z.object({
  questionCount: z.number().int().min(1).max(200),
  durationMinutes: z.number().int().min(1).max(300),
  marksPerQuestion: z.number().min(0.25).max(10),
  negativeMarking: z.number().min(0).max(10),
  allowMultipleAttempts: z.boolean(),
  autoGenerateDaily: z.boolean(),
});
export type ExamSettingsFormValues = z.infer<typeof examSettingsSchema>;

export const examSchema = z.object({
  title: optionalText(150),
  description: optionalText(1000),
  type: z.enum(['DAILY', 'MODEL']),
  examDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Choose a date'),
  questionCount: z.number().int().min(1).max(200),
  durationMinutes: z.number().int().min(1).max(300),
  marksPerQuestion: z.number().min(0.25).max(10),
  negativeMarking: z.number().min(0).max(10),
  allowMultipleAttempts: z.boolean(),
  accessLevel,
  isPublished: z.boolean(),
  subjectIds: z.array(z.string()),
});
export type ExamFormValues = z.infer<typeof examSchema>;

export const examUpdateSchema = examSchema.omit({ questionCount: true, subjectIds: true }).extend({
  title: z.string().trim().min(3, 'Title is required').max(150),
});
export type ExamUpdateFormValues = z.infer<typeof examUpdateSchema>;

// ── Premium ──
export const grantSchema = z.object({
  userId: z.string().min(1, 'Choose a user'),
  planId: z.string().nullable(),
  expiresAt: z.string(),
  note: optionalText(500),
});
export type GrantFormValues = z.infer<typeof grantSchema>;

/** Converts empty strings to null so optional columns are cleared rather than stored as "". */
export function emptyToNull<T extends Record<string, unknown>>(
  values: T,
): { [K in keyof T]: T[K] extends string ? string | null : T[K] } {
  return Object.fromEntries(
    Object.entries(values).map(([key, value]) => [
      key,
      typeof value === 'string' && value.trim() === '' ? null : value,
    ]),
  ) as never;
}
