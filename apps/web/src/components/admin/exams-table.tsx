'use client';

import { DataTableCard } from '@/components/admin/data-table-card';
import { DeleteButton } from '@/components/admin/delete-button';
import { EditLinkButton } from '@/components/admin/edit-link-button';
import { SearchInput } from '@/components/admin/search-input';
import { ToggleSwitch } from '@/components/admin/toggle-switch';
import { AccessBadge } from '@/components/common/access-badge';
import { Badge } from '@/components/ui/badge';
import { TableCell, TableHead, TableRow } from '@/components/ui/table';
import { useListQuery } from '@/hooks/use-list-query';
import { formatIsoDate } from '@/lib/format';
import { queryKeys } from '@/lib/query-keys';
import type { AdminExamRow } from '@/types/api';

function ExamRow({ exam }: { exam: AdminExamRow }) {
  return (
    <TableRow>
      <TableCell className="max-w-64">
        <p className="truncate font-medium">{exam.title}</p>
        <p className="text-muted-foreground flex items-center gap-1 text-xs">
          {exam.durationMinutes} min
          {exam.autoGeneratedFor && (
            <Badge variant="outline" className="py-0 text-[10px]">
              Auto
            </Badge>
          )}
        </p>
      </TableCell>
      <TableCell className="whitespace-nowrap">{formatIsoDate(exam.examDate)}</TableCell>
      <TableCell>
        <AccessBadge level={exam.accessLevel} />
      </TableCell>
      <TableCell className="text-right">{exam.questionCount}</TableCell>
      <TableCell className="text-right">{exam.attemptCount}</TableCell>
      <TableCell>
        <ToggleSwitch
          endpoint={`/admin/exams/${exam.id}`}
          field="isPublished"
          checked={exam.isPublished}
          label={`Publish ${exam.title}`}
          successMessage={(next) => (next ? 'Exam published' : 'Exam unpublished')}
        />
      </TableCell>
      <TableCell className="text-right whitespace-nowrap">
        <EditLinkButton href={`/admin/exams/${exam.id}`} label={`Manage ${exam.title}`} />
        {exam.attemptCount === 0 && (
          <DeleteButton endpoint={`/admin/exams/${exam.id}`} itemLabel="Exam" />
        )}
      </TableCell>
    </TableRow>
  );
}

export function ExamsTable() {
  const list = useListQuery<AdminExamRow>({
    endpoint: '/admin/exams',
    queryKey: queryKeys.admin.exams,
    pageSize: 15,
  });
  return (
    <div className="space-y-4">
      <SearchInput
        value={list.search}
        onChange={list.setSearch}
        placeholder="Search exams…"
        className="max-w-sm"
      />
      <DataTableCard
        query={list.query}
        onPageChange={list.setPage}
        emptyTitle="No exams yet"
        emptyDescription="Create a daily exam or enable auto-generation in the settings above."
        columns={
          <>
            <TableHead>Exam</TableHead>
            <TableHead>Date</TableHead>
            <TableHead>Access</TableHead>
            <TableHead className="text-right">Questions</TableHead>
            <TableHead className="text-right">Attempts</TableHead>
            <TableHead>Published</TableHead>
            <TableHead className="text-right">Actions</TableHead>
          </>
        }
      >
        {list.query.data?.items.map((exam) => (
          <ExamRow key={exam.id} exam={exam} />
        ))}
      </DataTableCard>
    </div>
  );
}
