'use client';

import { keepPreviousData, useQuery } from '@tanstack/react-query';
import { Pencil } from 'lucide-react';
import Link from 'next/link';
import { useState } from 'react';
import { DeleteButton } from '@/components/admin/delete-button';
import { SearchInput } from '@/components/admin/search-input';
import { ToggleSwitch } from '@/components/admin/toggle-switch';
import { AccessBadge } from '@/components/common/access-badge';
import { EmptyState } from '@/components/common/empty-state';
import { ErrorState } from '@/components/common/error-state';
import { ListSkeleton } from '@/components/common/list-skeleton';
import { Pager } from '@/components/common/pager';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from '@/components/ui/table';
import { useDebouncedValue } from '@/hooks/use-debounced-value';
import { api } from '@/lib/api';
import { formatIsoDate } from '@/lib/format';
import { queryKeys } from '@/lib/query-keys';
import type { AdminExamRow, Paginated } from '@/types/api';

export function ExamsTable() {
  const [search, setSearch] = useState('');
  const [page, setPage] = useState(1);
  const debouncedSearch = useDebouncedValue(search);
  const params = { search: debouncedSearch, page, pageSize: 15 };
  const { data, error, isPending, refetch } = useQuery({
    queryKey: queryKeys.admin.exams(params),
    queryFn: () => api.get<Paginated<AdminExamRow>>('/admin/exams', params),
    placeholderData: keepPreviousData,
  });

  return (
    <div className="space-y-4">
      <SearchInput
        value={search}
        onChange={(value) => {
          setSearch(value);
          setPage(1);
        }}
        placeholder="Search exams…"
        className="max-w-sm"
      />
      {isPending ? (
        <ListSkeleton />
      ) : error ? (
        <ErrorState error={error} onRetry={() => void refetch()} />
      ) : data.items.length === 0 ? (
        <EmptyState
          title="No exams yet"
          description="Create a daily exam or enable auto-generation in the settings above."
        />
      ) : (
        <Card className="py-2">
          <CardContent className="px-2 sm:px-4">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Exam</TableHead>
                  <TableHead>Date</TableHead>
                  <TableHead>Access</TableHead>
                  <TableHead className="text-right">Questions</TableHead>
                  <TableHead className="text-right">Attempts</TableHead>
                  <TableHead>Published</TableHead>
                  <TableHead className="text-right">Actions</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {data.items.map((exam) => (
                  <TableRow key={exam.id}>
                    <TableCell className="max-w-64">
                      <p className="truncate font-medium">{exam.title}</p>
                      <p className="text-muted-foreground flex gap-1 text-xs">
                        <span>{exam.durationMinutes} min</span>
                        {exam.autoGeneratedFor && (
                          <Badge variant="outline" className="py-0 text-[10px]">
                            Auto
                          </Badge>
                        )}
                      </p>
                    </TableCell>
                    <TableCell className="whitespace-nowrap">
                      {formatIsoDate(exam.examDate)}
                    </TableCell>
                    <TableCell>
                      <AccessBadge level={exam.accessLevel} />
                    </TableCell>
                    <TableCell className="text-right">{exam.questionCount}</TableCell>
                    <TableCell className="text-right">{exam.attemptCount}</TableCell>
                    <TableCell>
                      <ToggleSwitch
                        endpoint={`/admin/exams/${exam.id}`}
                        field="isPublished"
                        checked={exam.isPublished}
                        label={`Publish ${exam.title}`}
                        successMessage={(next) => (next ? 'Exam published' : 'Exam unpublished')}
                      />
                    </TableCell>
                    <TableCell className="text-right whitespace-nowrap">
                      <Button
                        asChild
                        variant="ghost"
                        size="icon"
                        aria-label={`Manage ${exam.title}`}
                      >
                        <Link href={`/admin/exams/${exam.id}`}>
                          <Pencil />
                        </Link>
                      </Button>
                      {exam.attemptCount === 0 && (
                        <DeleteButton endpoint={`/admin/exams/${exam.id}`} itemLabel="Exam" />
                      )}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
            <div className="px-2">
              <Pager
                page={data.meta.page}
                totalPages={data.meta.totalPages}
                total={data.meta.total}
                onPageChange={setPage}
              />
            </div>
          </CardContent>
        </Card>
      )}
    </div>
  );
}
