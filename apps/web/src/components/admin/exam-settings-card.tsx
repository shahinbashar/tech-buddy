'use client';

import { zodResolver } from '@hookform/resolvers/zod';
import { useQuery } from '@tanstack/react-query';
import { Loader2, Settings2 } from 'lucide-react';
import { useEffect } from 'react';
import { useForm } from 'react-hook-form';
import { NumberField, SwitchField } from '@/components/admin/form-fields';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Form } from '@/components/ui/form';
import { useAdminMutation } from '@/hooks/use-admin-mutation';
import { examSettingsSchema, type ExamSettingsFormValues } from '@/lib/admin-schemas';
import { api } from '@/lib/api';
import { queryKeys } from '@/lib/query-keys';
import type { ExamSettings } from '@/types/api';

export function ExamSettingsCard() {
  const { data } = useQuery({
    queryKey: queryKeys.admin.examSettings,
    queryFn: () => api.get<ExamSettings>('/admin/exams/settings'),
  });
  const form = useForm<ExamSettingsFormValues>({ resolver: zodResolver(examSettingsSchema) });

  useEffect(() => {
    if (data) {
      form.reset({
        questionCount: data.questionCount,
        durationMinutes: data.durationMinutes,
        marksPerQuestion: data.marksPerQuestion,
        negativeMarking: data.negativeMarking,
        allowMultipleAttempts: data.allowMultipleAttempts,
        autoGenerateDaily: data.autoGenerateDaily,
      });
    }
  }, [data, form]);

  const save = useAdminMutation<ExamSettingsFormValues>({
    mutationFn: (values) => api.put('/admin/exams/settings', values),
    successMessage: 'Exam settings saved',
  });

  return (
    <Card className="gap-4">
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-base">
          <Settings2 className="size-4" aria-hidden /> Default daily exam settings
        </CardTitle>
        <CardDescription>
          Used for new exams and for the automatically generated daily exam (free, published
          questions only).
        </CardDescription>
      </CardHeader>
      <CardContent>
        {data ? (
          <Form {...form}>
            <form
              onSubmit={form.handleSubmit((values) => save.mutate(values))}
              className="space-y-4"
              noValidate
            >
              <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
                <NumberField
                  control={form.control}
                  name="questionCount"
                  label="Questions"
                  min={1}
                />
                <NumberField
                  control={form.control}
                  name="durationMinutes"
                  label="Duration (minutes)"
                  min={1}
                />
                <NumberField
                  control={form.control}
                  name="marksPerQuestion"
                  label="Marks per question"
                  step={0.25}
                  min={0.25}
                />
                <NumberField
                  control={form.control}
                  name="negativeMarking"
                  label="Negative marking"
                  step={0.25}
                  min={0}
                />
              </div>
              <div className="grid gap-3 md:grid-cols-2">
                <SwitchField
                  control={form.control}
                  name="autoGenerateDaily"
                  label="Auto-generate daily exam"
                  description="Creates today's exam when none is published"
                />
                <SwitchField
                  control={form.control}
                  name="allowMultipleAttempts"
                  label="Allow multiple attempts"
                  description="Default for new exams"
                />
              </div>
              <Button type="submit" disabled={save.isPending || !form.formState.isDirty}>
                {save.isPending && <Loader2 className="animate-spin" />}
                Save settings
              </Button>
            </form>
          </Form>
        ) : (
          <Loader2 className="text-muted-foreground animate-spin" aria-label="Loading settings" />
        )}
      </CardContent>
    </Card>
  );
}
